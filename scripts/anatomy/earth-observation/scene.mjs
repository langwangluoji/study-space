export function scene(mode,p,{cache=true}={}) {
 const model=evaluate(mode,p),info=catalog[mode],R=A.recorder(P);
 function put(name,at,paths,shape,tone='mid',inner='') {const s=R.solid(shape);R.put({name,at,shapes:[s],svg:k.solidSvg(paths,{tone,lit:tone==='lit',inner})});}
 function slab(name,x,y,w,d,z,h,tone='mid',detail=true){const plan={x,y,w,d,r:Math.min(1.4,w/8,d/8)},inner=detail&&w>12&&d>10?k.lineSvg(k.planOutline(k.insetPlan(plan,2),z+h,P),{tone:'faint'}):'';put(name,[x+w/2,y+d/2,z+h/2],k.slabOf(plan,z,h,P,5,.4),A.slab(plan,z,h,{name}),tone,inner);}
 function cyl(name,x,y,r,z,h,tone='mid',ticks=false){let inner='';if(ticks){inner=k.lineSvg(k.ring(x,y,r-1,z+h,P,40),{tone:'lo'});const t=k.radialTicks(x,y,r-1,40,5,z+h,[1,2.2],P);inner+=k.lineSvg(t.minor+t.major,{tone:'lo'});}put(name,[x,y,z+h/2],k.cylinder(x,y,r,z,h,P,48,.3),A.cylinder(x,y,r,z,h,{name}),tone,inner);}
 function ball(name,center,r,tone='hi'){put(name,center,G.sphereOf(center,r,P),A.ball(center,r,{name}),tone);}
 function rod(name,from,to,r,tone='mid'){const F=G.frameAlong(from,G.sub3(to,from)),len=G.len3(G.sub3(to,from));put(name,G.mul3(G.add3(from,to),.5),G.solidOf([[0,r],[len,r]],F,P,{steps:20}),A.disc(F,0,len,r,{name}),tone);}
 function polyLine(name,points,tone='hi',closed=false){const pts=points.map(v=>k.iso(v,P)),d=pts.map((q,i)=>`${i?'L':'M'}${q[0].toFixed(3)},${q[1].toFixed(3)}`).join('')+(closed?'Z':'');const dots=closed?'':k.dotsSvg([pts[0],pts.at(-1)],{size:.6,tone});return k.lineSvg(d,{tone})+dots;}
 // A metrology bench: rubber feet, adjusting pads, cast base and fixing screws.
 for(const x of [-125,125])for(const y of [-58,58]) {cyl(`stand.foot.${x}.${y}`,x,y,6,0,3,'lo');cyl(`foot.adjust.${x}.${y}`,x,y,4.5,3,2);}
 slab('bench',-143,-74,286,148,5,10,'lo');
 for(const x of [-133,133])for(const y of [-64,64])cyl(`base.fastener.${x}.${y}`,x,y,1.3,15,.7,'lo');
 slab('scale.strip',-129,57,249,7,15,.7,'lo',false);
 for(let i=0;i<=16;i++)slab(`scale.engraving.${i}`,-125+i*15,57,.35,i%4?2:4,15.7,.15,i%4?'lo':'mid',false);
 // A recording instrument whose trace is generated by the same model as the mechanism.
 slab('scope.plinth',70,-38,60,77,15,4);
 slab('scope.case',72,-36,56,73,19,28);
 slab('scope.bezel.back',74,-34,52,5,47,3,'hi');
 slab('scope.bezel.front',74,27,52,5,47,3,'hi');
 slab('scope.bezel.left',74,-29,4,56,47,3,'hi');
 slab('scope.bezel.right',122,-29,4,56,47,3,'hi');
 slab('scope.screen',78,-29,44,56,47,.4,'lo',false);
 for(const y of [-22,-8,6,20])slab(`scope.grid.${y}`,78,y,44,.18,47.4,.08,'lo',false);
 for(const x of [85,96,107,118])slab(`scope.grid.${x}`,x,-29,.18,56,47.4,.08,'lo',false);
 for(const y of [-21,0,21]) {cyl(`scope.knob.${y}`,135,y,3,15,8);}
 for(const y of [-22,-11,0,11,22])slab(`scope.vent.${y}`,73,y,2,4,47,.25,'lo',false);
 const graph=model.series.map(([t,v])=>[80+Math.max(0,Math.min(1,t))*40,24-(Math.max(-1,Math.min(1,v))+1)*24,47.7]);
 // Traces live on the screen plane; terminal dots end each ink trace.
 let screenInk=graph.length?polyLine('scope.trace',graph,'hi'):'';
 if(mode==='speckle')screenInk=model.series.map(([_,v],i)=>{const x=80+(i%8)*5,y=-26+Math.floor(i/8)*6.5,points=[[x,y],[x+4.4,y],[x+4.4,y+5.8],[x,y+5.8]].map(([a,b])=>k.iso([a,b,47.7],P));return `<path d="${k.pathOf(points,true)}" fill="currentColor" opacity="${Math.max(.03,Math.min(1,v*1.4)).toFixed(4)}"/>`;}).join('');
 let screenItem=R.items.find(x=>x.name==='scope.screen');screenItem.svg+=screenInk;
 // All accessories sit on one rotary table, with a real edge scale and hand wheels.
 cyl('turntable.plinth',-46,0,55,15,5,'lo');
 cyl('turntable.bearing',-46,0,45,20,3);
 cyl('turntable.face',-46,0,50,23,3,'hi',true);
 for(const [x,y] of [[-105,-55],[-105,50]]) {slab(`wheel.mount.${y}`,x-5,y-5,10,10,15,5);cyl(`wheel.${y}`,x,y,4.2,20,5,'mid',true);}
 // A paired ruler across the front of the turntable is shared by the distance and scanner modules.
 if(info.kind==='terrain') {
   // A solid extruded triangular section; both slopes are the selected angles.
   // Limit height to keep the shallow-slope footprint inside the rotary face.
   const ta=Math.tan(rad(p.alpha)),tb=Math.tan(rad(p.beta)),height=Math.min(25,40*ta,40*tb);
   const left=ta>0?height/ta:40,right=tb>0?height/tb:40;
   const poly=[[-left,0],[right,0],[0,height]],F={o:[-46,-18,26],a:[0,1,0],u:[1,0,0],v:[0,0,1]};
   const world=(q,y)=>[-46+q[0],y,26+q[1]],a=poly.map(q=>world(q,-18)),b=poly.map(q=>world(q,18));
   const path=pts=>k.pathOf(pts.map(q=>k.iso(q,P)),true);
   const front=path(b),slope1=path([a[0],a[2],b[2],b[0]]),slope2=path([a[2],a[1],b[1],b[2]]);
   const paths={fill:path([...a,...b].sort((u,v)=>u[0]-v[0])),shades:[front,'',slope2,''],top:slope1,outline:front+slope1+slope2,crease:''};
   // Fill is the convex projected hull; the recorded volume is this same triangular prism.
   paths.fill=front+slope1+slope2;
   put('terrain.block',[-46,0,26+height/3],paths,A.prism(F,poly,0,36,{name:'terrain.block'}),'hi');
   slab('radar.foot',16,-9,16,18,15,6);slab('radar.pedestal',20,-5,8,10,21,56);
   slab('radar.housing',16,-9,16,18,77,12);cyl('radar.antenna',24,0,6,89,2,'lit');
 } else if(['rail','radar'].includes(info.kind)) {
  for(const y of [-38,38]) {slab(`rail.mount.left.${y}`,-112,y-4,9,8,15,14);slab(`rail.mount.right.${y}`,29,y-4,9,8,15,14);slab(`rail.${y}`,-103,y-2,132,4,26,3);}
  const x=mode==='reduction'?-80+(p.D-100)/2900*90:-40+(['speckle','coherence','penetration'].includes(mode)?0:model.travel);
  // A bridge rides on both rails. Its lower face is flush with the rail tops.
  slab('carriage',x-11,-41,22,82,29,5,'hi');
  for(const y of [-36,36])slab(`carriage.clamp.${y}`,x-8,y-3,16,6,34,3);
  const rise=mode==='reduction'?p.H2/10:0;
  slab('sensor.mount',x-7,-7,14,14,34,8+rise);
  slab('sensor.body',x-10,-10,20,20,42+rise,18,'mid');
  cyl('sensor.aperture',x,0,6,60+rise,3,'lit');
  for(const dx of [-7,7])cyl(`sensor.screw.${dx}`,x+dx,-7,1,60+rise,.7,'lo');
  // Fixed reference reflector on its own riser.
  const referenceRise=mode==='reduction'?p.H1/10:0;
  slab('reference.plinth',-120,-10,12,20,15,34+referenceRise);
  slab('reference.reflector',-120,-10,12,20,49+referenceRise,2,'hi');
  if(mode==='midpoint') {const mid=(-114+x)/2;slab('midpoint.bridge',mid-4,-41,8,82,29,2,'hi');cyl('midpoint.probe',mid,0,1.5,31,20,'hi');ball('midpoint.head',[mid,0,52.5],1.5,'lit');}
  if(mode==='phase') {cyl('phase.dial',-5,50,5.5,15,3,'hi',true);const a=rad(model.angle),needle=[[-5,50,18.05],[-5+4*Math.cos(a),50+4*Math.sin(a),18.05]];R.items.find(v=>v.name==='phase.dial').svg+=polyLine('phase.pointer',needle,'lit');}
  if(mode==='penetration') {for(let j=0;j<3;j++)slab('dielectric.layer.'+j,-91,-65,22,14,15+j*4,4,j===2?'hi':'mid');}
 } else if(info.kind==='optical') {
  // Source, sample wheel and goniometric receiver, all mounted to the rotary face.
  slab('lamp.foot',-92,-11,16,22,26,5);slab('lamp.pillar',-88,-5,8,10,31,25);
  slab('lamp.case',-96,-12,24,24,56,20);cyl('lamp.shutter',-84,0,mode==='energy'?6*Math.sqrt(p.incident/100):6,76,2,'hi');
  cyl('sample.spindle',-46,0,5,26,12);cyl('sample.holder',-46,0,17,38,3,'mid',true);cyl('sample.surface',-46,0,13,41,1,'lit');
  const receiverAngle=mode==='reflectance'?p.view:mode==='radiometry'?p.angle:20;
  const theta=rad(receiverAngle),cx=-46+32*Math.cos(theta),cy=32*Math.sin(theta);
  cyl('receiver.shoe',cx,cy,5,26,3);cyl('receiver.post',cx,cy,2.2,29,23);
  slab('receiver.housing',cx-7,cy-7,14,14,52,14,'hi');cyl('receiver.pupil',cx,cy,4,66,2,'mid');
  for(const x of [-92,-76])for(const y of [-8,8])cyl(`lamp.screw.${x}.${y}`,x,y,.8,76,.6,'lo');
  if(mode==='energy') {
    const tau=(1-p.reflect)*p.transmit,alpha=1-p.reflect-tau;
    for(const [i,fraction] of [p.reflect,tau,alpha].entries())slab('energy.column.'+i,-92+i*18,-64,8,8,15,2+fraction*p.incident/100*25,'hi',false);
  }
 } else if(info.kind==='rotary') {
  // A fixed target pin and an engraved orthogonal coordinate reticle on a turntable.
  // Passive operation rotates only the reticle; active operation rotates the target.
  const t=rad(p.active?0:p.angle),target=rad(p.active?p.angle:0),dial=R.items.find(v=>v.name==='turntable.face');
  const axis=(angle)=>[[-46-38*Math.cos(angle),-38*Math.sin(angle),26.05],[-46+38*Math.cos(angle),38*Math.sin(angle),26.05]];
  dial.svg+=polyLine('reticle.x',axis(t),'hi')+polyLine('reticle.y',axis(t+Math.PI/2),'mid');
  for(const sign of [-1,1])for(let n=1;n<=6;n++){const d=sign*n*5,x=-46+d*Math.cos(t),y=d*Math.sin(t);dial.svg+=polyLine('reticle.tick',[[x-1.5*Math.sin(t),y+1.5*Math.cos(t),26.05],[x+1.5*Math.sin(t),y-1.5*Math.cos(t),26.05]],'lo');}
  const tx=-46+28*Math.cos(target),ty=28*Math.sin(target);cyl('target.pin',tx,ty,1.4,26,12,'lit');ball('target.head',[tx,ty,39.4],1.4,'lit');
 } else {
  // Rotating globe on a centre spindle. Its ellipsoidal profile is the actual selected f.
  const f=mode==='geodesic'?0:model.globeF,rx=40,rz=rx*(1-f),cz=62+rz,F=G.frameAlong([-46,0,cz],[0,0,1]);
  cyl('globe.socket',-46,0,10,26,5);cyl('globe.spindle',-46,0,3,31,31);
  const radius=s=>rx*Math.sqrt(Math.max(0,1-(s/rz)**2));
  const profile=Array.from({length:65},(_,i)=>{const t=-Math.PI/2+i*Math.PI/64;return [rz*Math.sin(t),rx*Math.cos(t),1];});
  put('globe.body',[-46,0,cz],G.solidOf(profile,F,P,{steps:96,smooth:{slope:s=>-rx*s/(rz*rz*Math.sqrt(Math.max(1e-12,1-s*s/(rz*rz))))}}),A.solid(F,profile,{name:'globe.body',radius}),'hi');
  // Engraved graticule on the physical globe, ending at its visible silhouette.
  // It uses the ellipsoid itself, rather than an unrelated decorative wireframe.
  const cam=k.cameraOf(P),viewer=[cam.cosA*cam.cosE,cam.sinA*cam.cosE,cam.sinE],gitem=R.items.find(v=>v.name==='globe.body');
  function surfaceCurve(points){let run=[];const flush=()=>{if(run.length>1)gitem.svg+=polyLine('graticule',run,'lo');run=[];};for(const q of points){const n=[(q[0]+46)/(rx*rx),q[1]/(rx*rx),(q[2]-cz)/(rz*rz)],front=n.reduce((s,v,i)=>s+v*viewer[i],0)>=0;if(front)run.push(q);else flush();}flush();}
  for(const lat of [-60,-30,0,30,60]){const t=rad(lat);surfaceCurve(Array.from({length:361},(_,i)=>{const l=rad(i);return [-46+(rx+.02)*Math.cos(t)*Math.cos(l),(rx+.02)*Math.cos(t)*Math.sin(l),cz+(rz+.02)*Math.sin(t)];}));}
  for(const lon of [0,30,60,90,120,150]){const l=rad(lon);surfaceCurve(Array.from({length:361},(_,i)=>{const t=rad(i);return [-46+(rx+.02)*Math.cos(t)*Math.cos(l),(rx+.02)*Math.cos(t)*Math.sin(l),cz+(rz+.02)*Math.sin(t)];}));}
  const b=rad(mode==='orbit'?0:(p.B??35)),longitude=rad(mode==='orbit'?model.angle:0);
  const normal=[Math.cos(b)*Math.cos(longitude),Math.cos(b)*Math.sin(longitude),Math.sin(b)];
  const denom=Math.sqrt(rx*rx*Math.cos(b)**2+rz*rz*Math.sin(b)**2),surface=[-46+rx*rx*normal[0]/denom,rx*rx*normal[1]/denom,cz+rz*rz*normal[2]/denom];
  const outside=G.add3(surface,G.mul3(normal,1.4));ball('globe.target',outside,1.4,'lit');
  if(mode==='orbit') {const tip=G.add3(outside,G.mul3(normal,14+model.travel));rod('orbit.model.arm',G.add3(outside,G.mul3(normal,1.4)),tip,.7);ball('orbit.satellite',G.add3(tip,G.mul3(normal,3)),3,'lit');}
  else {
    const extension=mode==='latitude'?(p.h/6378137*40*200):0,tip=G.add3(outside,G.mul3(normal,10+extension));
    rod('survey.normal',G.add3(outside,G.mul3(normal,1.4)),tip,.65,'hi');ball('survey.probe',G.add3(tip,G.mul3(normal,1.5)),1.5,'lit');
    if(mode==='curvature'||mode==='metric') {
      const north=[-Math.sin(b),0,Math.cos(b)],east=[0,1,0],origin=G.add3(tip,G.mul3(normal,3));
      // Tangent-arm bearings sit on the probe ball, flush at its outer pole.
      if(mode==='curvature') {const joint=G.add3(origin,normal);ball('curvature.joint',joint,1,'hi');const A=rad(p.A),direction=north.map((v,i)=>v*Math.cos(A)+east[i]*Math.sin(A)),end=G.add3(joint,G.mul3(direction,15));rod('curvature.direction',G.add3(joint,direction),end,.8,'hi');ball('curvature.roller',G.add3(end,G.mul3(direction,1.6)),1.6,'lit');}
      else {const joint=G.add3(origin,normal);ball('metric.joint',joint,1,'hi');for(const [name,direction,length] of [['north',north,15],['east',east,15*model.e.longitudeScale/model.e.latitudeScale]]){const end=G.add3(joint,G.mul3(direction,Math.max(2,length)));rod('metric.'+name,G.add3(joint,direction),end,.65,'hi');ball('metric.'+name+'.end',G.add3(end,G.mul3(direction,1.3)),1.3,'lit');}}
    }
    if(mode==='geodesic') {
      const route=Array.from({length:81},(_,i)=>{const r=sphereRoute(p.B,p.A,p.S*1000*i/80),b=rad(r.B2),l=rad(r.L2);return [-46+(rx+.03)*Math.cos(b)*Math.cos(l),(rx+.03)*Math.cos(b)*Math.sin(l),cz+(rx+.03)*Math.sin(b)];});surfaceCurve(route);
    }
  }
 }
 const settled=A.settle(R,P,{step:.25,rasterCache:cache?rasterCache:null,pairCache:cache?pairCache:null});
 while(rasterCache.size>160)rasterCache.delete(rasterCache.keys().next().value);
 const svg=k.figureSvg({width:720,height:390,label:info.title+'。'+info.note,body:[`<path class="iso-halo" d="${k.haloOf({x:-143,y:-74,w:286,d:148,r:4},0,10,P)}"/>`,...R.items.sort((a,b)=>a.key-b.key).map(v=>v.svg)]});
 return {svg,R,model,parts:R.solids.length,settled};
}
