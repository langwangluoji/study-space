export const P=k.fitProjection([[-145,-76,0],[145,76,0],[-85,-45,132],[130,45,85]],720,390,{pad:28,azimuth:36});
const esc=s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;');
// At most one raster per physical part name, independent of slider history.
const rasterCache=new Map();
